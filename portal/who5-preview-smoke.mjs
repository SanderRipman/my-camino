import fs from 'node:fs';
import {Script} from 'node:vm';
const html=fs.readFileSync(new URL('./who5-preview.html',import.meta.url),'utf8');
const entry=fs.readFileSync(new URL('./index.html',import.meta.url),'utf8');
const ok=(v,m)=>{if(!v)throw Error(m)};
ok(html.includes('<meta name="robots" content="noindex,nofollow">'),'WHO-5 preview must not be indexed');
ok(html.includes('Ingen svar sendes, lagres, eksporteres'),'Must disclose no-write nature');
ok(html.includes('Bruk fiktive svar'),'Must require fictitious test data');
ok(html.includes('de siste to ukene'),'Missing WHO-5 recall window');
ok((html.match(/'Jeg har /g)||[]).length>=3,'WHO-5 questions not present');
for(const phrase of ['Jeg har vært glad','Jeg har følt meg rolig','Jeg har følt meg aktiv','Jeg har våknet','Mitt daglige liv'])ok(html.includes(phrase),'Missing WHO-5 dimension: '+phrase);
ok(html.includes('sum*4'),'Standard WHO-5 0–100 scoring absent');
ok(html.includes('if(!selected)'),'Five required questions not enforced');
ok(!/\b(?:fetch|localStorage|sessionStorage|indexedDB|XMLHttpRequest|sendBeacon)\b/.test(html),'Preview must not access network or persistent client stores');
ok(entry.includes('href="./who5-preview.html"'),'Demo form library missing WHO-5 link');
const scripts=[...html.matchAll(/<script>([^]*?)<\/script>/g)].map(m=>m[1]);
ok(scripts.length===1,'Expected exactly one self-contained inline WHO-5 script');
new Script(scripts[0],{filename:'who5-preview-inline.js'});
console.log('WHO-5 no-write demo smoke: OK');